extern  meUInt  meUniToUpper(meUInt uc);
extern  meUInt  meUniFold(meUInt uc);
extern  int     meUniFoldSources(meUInt fc, meUInt *cs, int max);
extern  const char *meUniVersion(void);

#endif /* __EUNICODE_H */
